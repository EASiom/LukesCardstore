function detectLanguage() {
  const browserLanguages = navigator.languages?.length ? navigator.languages : [navigator.language];
  return browserLanguages[0]?.toLowerCase().startsWith('en') ? 'en' : 'de';
}

function getSavedLanguage() {
  try {
    const savedLanguage = localStorage.getItem('lukes-cardshop-language');
    return savedLanguage === 'en' || savedLanguage === 'de' ? savedLanguage : detectLanguage();
  } catch (error) {
    return detectLanguage();
  }
}

window.siteLanguage = getSavedLanguage();
window.t = (key) => translations[window.siteLanguage][key] || translations.de[key] || key;
window.getLocalizedEventText = (event, field) => (
  window.siteLanguage === 'en' && event[`${field}En`] ? event[`${field}En`] : event[field]
);

function applyLanguage() {
  document.documentElement.lang = window.siteLanguage;
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    element.textContent = window.t(element.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    element.placeholder = window.t(element.dataset.i18nPlaceholder);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((element) => {
    element.setAttribute('aria-label', window.t(element.dataset.i18nAria));
  });
  document.querySelectorAll('[data-i18n-title]').forEach((element) => {
    element.title = window.t(element.dataset.i18nTitle);
  });
  const pageTitle = document.querySelector('title[data-i18n]');
  if (pageTitle) document.title = window.t(pageTitle.dataset.i18n);

  const switchControl = document.getElementById('languageSwitch');
  if (switchControl) {
    switchControl.setAttribute('aria-checked', String(window.siteLanguage === 'en'));
    switchControl.setAttribute(
      'aria-label',
      window.siteLanguage === 'en' ? 'Switch language to German' : 'Sprache auf Englisch ändern'
    );
    switchControl.querySelector('.language-switch-knob').style.transform =
      window.siteLanguage === 'en' ? 'translateX(22px)' : 'translateX(0)';
  }
}

function addLanguageSwitch() {
  const control = document.createElement('button');
  control.id = 'languageSwitch';
  control.className = 'language-switch';
  control.type = 'button';
  control.setAttribute('role', 'switch');
  control.innerHTML = '<span>DE</span><span class="language-switch-track"><span class="language-switch-knob"></span></span><span>EN</span>';
  control.addEventListener('click', () => {
    window.siteLanguage = window.siteLanguage === 'de' ? 'en' : 'de';
    try {
      localStorage.setItem('lukes-cardshop-language', window.siteLanguage);
    } catch (error) {
      // Keep the language change active for this page if storage is unavailable.
    }
    applyLanguage();
    document.dispatchEvent(new CustomEvent('languagechange', { detail: window.siteLanguage }));
  });
  document.body.appendChild(control);
  applyLanguage();
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', addLanguageSwitch, { once: true });
} else {
  addLanguageSwitch();
}
